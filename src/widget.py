def mask_account_card(info: str) -> str:
    """
    Маскирует номер карты или счета в зависимости от типа.

    Аргументы:
        info: Строка вида "Visa Platinum 7000792289606361" или "Счет 73654108430135874305"

    Возвращает:
        Строку с маскированным номером.
    """
    parts = info.split(' ', 1)
    if len(parts) != 2:
        raise ValueError("Некорректный формат строки: должно быть две части - тип и номер")
    card_type, number = parts
    number = number.strip()

    if card_type.lower() == 'счет':
        # Маскировка для счета: первые 4 цифры видны, остальные заменены на "*"
        masked_number = f"**{number[-4:]}"
        return f"{card_type} {masked_number}"

    # Для карт: оставить тип, и маскировать номер
    # Считаем, что номер содержит только цифры
    if not number.isdigit():
        raise ValueError("Номер карты или счета должен содержать только цифры")

    # Маскировка номера
    # Пример: 7000792289606361 -> 7000 79** **** 6361
    # Многие маскировки используют группировку по 4 цифры
    # Но по условию, для карт возвращать "тип + маскированный номер"
    # Для разной маскировки используем шаблон:
    # первые 4 цифры — открытые, затем по требованию
    # В нашем случае, пример показывает, что отображается:
    # первые 4 цифры, потом 2 символа, затем ***, затем еще *** и последние 4 цифры

    # Создадим условный шаблон:
    # оставляем первые 4 цифры
    part1 = number[:4]
    # потом 2 цифры (можно оставить или заменить на **)
    part2 = number[4:6]
    # затем 4 звездочки
    stars = "****"
    # затем еще 4 звездочки
    stars2 = "****"
    # последние 4 цифры
    part3 = number[-4:]

    masked = f"{part1} {part2}** {stars} {stars2} {part3}"

    return f"{card_type} {masked}"


def get_date(date_str: str) -> str:
    """
    Преобразует строку с датой из формата ISO8601 в формат "ДД.ММ.ГГГГ".

    Вход:
        "2024-03-11T02:26:18.671407"
    Выход:
        "11.03.2024"
    """
    from datetime import datetime
    dt = datetime.fromisoformat(date_str)
    return dt.strftime("%d.%m.%Y")